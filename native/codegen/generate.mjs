import { readFile, writeFile, mkdir, readdir, mkdtemp, rm } from "node:fs/promises";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { tmpdir } from "node:os";
import { spawnSync } from "node:child_process";
import { normalize } from "./normalize.mjs";
import { emitGo } from "./emit-go.mjs";
import { emitPython } from "./emit-python.mjs";
import { emitRust } from "./emit-rust.mjs";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const schema = process.env.OCTO_CODEGEN_SCHEMA
  ? new URL("file://" + resolve(process.env.OCTO_CODEGEN_SCHEMA) + "/")
  : new URL("../../packages/octo-runtime-protocol/schema/", import.meta.url);
const ir = await normalize(schema);
const outputRoot = process.env.OCTO_CODEGEN_OUTPUT
  ? resolve(process.env.OCTO_CODEGEN_OUTPUT)
  : root;
const outputs = { ...emitGo(ir), ...emitPython(ir), ...emitRust(ir) };
for (const [lang, ext, dest] of [
  ["go", "go", "native/go"],
  ["rust", "rs", "native/rust/src/generated"],
  ["python", "py", "native/python/src/octo_runtime"]
]) {
  for (const name of (await readdir(resolve(root, `native/codegen/templates/${lang}`))).sort())
    if (name.endsWith("." + ext))
      outputs[`${dest}/generated_${name}`] =
        `// Code generated by native/codegen/generate.mjs; DO NOT EDIT.\n`.replace(
          "//",
          lang === "python" ? "#" : "//"
        ) + (await readFile(resolve(root, `native/codegen/templates/${lang}/${name}`), "utf8"));
}
// 格式化使用构建机工具，不进入 SDK 安装/运行路径。
const temp = await mkdtemp(resolve(tmpdir(), "octo-gen-"));
try {
  for (const [path, data] of Object.entries(outputs)) {
    const target = resolve(temp, path);
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, data);
  }
  const goFiles = Object.keys(outputs)
    .filter((p) => p.endsWith(".go"))
    .map((p) => resolve(temp, p));
  if (goFiles.length) {
    const result = spawnSync("gofmt", ["-w", ...goFiles], { encoding: "utf8" });
    if (result.status !== 0) throw Error(result.stderr || "gofmt required for generation");
  }
  for (const path of Object.keys(outputs))
    outputs[path] = await readFile(resolve(temp, path), "utf8");
  const rustFiles = Object.keys(outputs)
    .filter((p) => p.endsWith(".rs"))
    .map((p) => resolve(temp, p));
  if (rustFiles.length) {
    const result = spawnSync("rustfmt", ["--edition", "2021", ...rustFiles], { encoding: "utf8" });
    if (result.status !== 0) throw Error(result.stderr || "rustfmt required for generation");
  }
  for (const path of Object.keys(outputs))
    outputs[path] = await readFile(resolve(temp, path), "utf8");
  const generatorHash = createHash("sha256");
  async function hashTree(dir) {
    for (const entry of (await readdir(resolve(root, dir), { withFileTypes: true })).sort((a, b) =>
      a.name.localeCompare(b.name)
    )) {
      const path = dir + "/" + entry.name;
      if (entry.isDirectory()) await hashTree(path);
      else generatorHash.update(path + "\0" + (await readFile(resolve(root, path), "utf8")));
    }
  }
  await hashTree("native/codegen");
  const hash = createHash("sha256");
  for (const [name, text] of ir.sources) hash.update(name + "\0" + text);
  outputs["native/generated-manifest.json"] =
    JSON.stringify(
      {
        revision: 1,
        sourceHash: hash.digest("hex"),
        generatorHash: generatorHash.digest("hex"),
        files: Object.keys(outputs).sort()
      },
      null,
      2
    ) + "\n";
  let previous;
  try {
    previous = JSON.parse(
      await readFile(resolve(outputRoot, "native/generated-manifest.json"), "utf8")
    );
  } catch {}
  const stale = (previous?.files ?? []).filter((p) => !(p in outputs));
  async function findGenerated(dir) {
    let entries;
    try {
      entries = await readdir(resolve(outputRoot, dir), { withFileTypes: true });
    } catch {
      return [];
    }
    const found = [];
    for (const entry of entries) {
      const path = dir + "/" + entry.name;
      if (entry.isDirectory()) {
        if (!["target", ".venv", "__pycache__"].includes(entry.name))
          found.push(...(await findGenerated(path)));
      } else if (
        (entry.name.startsWith("generated_") || dir === "native/rust/src/generated") &&
        path !== "native/generated-manifest.json" &&
        !Object.hasOwn(outputs, path)
      ) {
        found.push(path);
      }
    }
    return found;
  }
  for (const p of await findGenerated("native")) if (!stale.includes(p)) stale.push(p);
  if (stale.some((p) => !p.startsWith("native/") || p.includes("..")))
    throw Error("Unsafe generated manifest path");
  if (process.argv.includes("--check")) {
    const drift = [...stale];
    for (const [path, data] of Object.entries(outputs)) {
      let old;
      try {
        old = await readFile(resolve(outputRoot, path), "utf8");
      } catch {}
      if (old !== data) drift.push(path);
    }
    if (drift.length) throw Error("Generated drift:\n" + drift.join("\n"));
    console.log(`Generated files match (${Object.keys(outputs).length})`);
  } else {
    for (const path of stale) await rm(resolve(outputRoot, path));
    for (const [path, data] of Object.entries(outputs)) {
      await mkdir(dirname(resolve(outputRoot, path)), { recursive: true });
      await writeFile(resolve(outputRoot, path), data);
    }
    console.log(`Generated ${Object.keys(outputs).length} files`);
  }
} finally {
  await rm(temp, { recursive: true, force: true });
}
