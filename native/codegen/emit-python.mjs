import { snake } from "./normalize.mjs";
// JSON text in literals must not be rewritten: strings use JSON quoting separately.
function literal(v) {
  if (v === null) return "None";
  if (v === true) return "True";
  if (v === false) return "False";
  if (Array.isArray(v)) return "[" + v.map(literal).join(",") + "]";
  if (typeof v === "object")
    return (
      "{" +
      Object.entries(v)
        .map(([k, x]) => JSON.stringify(k) + ":" + literal(x))
        .join(",") +
      "}"
    );
  return JSON.stringify(v);
}
export function emitPython(ir) {
  const { nodes, roots, methods, behavior } = ir;
  const out = [
    "# Code generated by native/codegen/generate.mjs; DO NOT EDIT.",
    "from __future__ import annotations",
    "from typing import Any, Literal, NotRequired, Required, TypedDict, Union, TypeAlias",
    "from decimal import Decimal"
  ];
  function typ(id) {
    const n = nodes[id],
      s = n.schema;
    if (n.ref !== undefined) return nodes[n.ref].name;
    if (s.properties) return n.name;
    if (s.oneOf || s.anyOf)
      return "Union[" + (n.branches.oneOf ?? n.branches.anyOf).map(typ).join(", ") + "]";
    if (s.const !== undefined) return "Literal[" + literal(s.const) + "]";
    if (s.enum) return "Literal[" + s.enum.map(literal).join(", ") + "]";
    if (s.type === "array") return "list[" + typ(n.branches.items) + "]";
    const t = (x) =>
      ({
        string: "str",
        integer: "int",
        number: "Union[int, Decimal]",
        boolean: "bool",
        null: "None",
        object: "dict[str, Any]"
      })[x] ?? "Any";
    return Array.isArray(s.type) ? "Union[" + s.type.map(t).join(", ") + "]" : t(s.type);
  }
  for (const n of nodes) {
    const s = n.schema;
    if (s.properties) {
      out.push(
        `${n.name} = TypedDict(${JSON.stringify(n.name)}, {${Object.entries(n.properties)
          .map(
            ([k, id]) =>
              JSON.stringify(k) +
              ": " +
              (s.required?.includes(k) ? "Required" : "NotRequired") +
              "[" +
              JSON.stringify(typ(id)) +
              "]"
          )
          .join(", ")}})`
      );
    } else {
      out.push(`${n.name}: TypeAlias = ${JSON.stringify(typ(n.id))}`);
    }
  }
  const ruleNodes = nodes.map((n) => {
    const s = n.schema;
    const r = {};
    if (n.ref !== undefined) r.ref = n.ref;
    for (const k of [
      "type",
      "enum",
      "const",
      "required",
      "minimum",
      "maximum",
      "minLength",
      "maxLength",
      "minItems",
      "maxItems",
      "minProperties",
      "maxProperties",
      "uniqueItems",
      "pattern",
      "format"
    ])
      if (s[k] !== undefined) r[k] = s[k];
    if (s.properties) r.properties = n.properties;
    if (s.additionalProperties === false) r.strict = true;
    Object.assign(r, n.branches);
    const x = Object.fromEntries(Object.entries(s).filter(([k]) => k.startsWith("x-")));
    if (Object.keys(x).length) r.extensions = x;
    return r;
  });
  const rules =
    [
      "# Code generated by native/codegen/generate.mjs; DO NOT EDIT.",
      `RULES = ${literal(ruleNodes)}`,
      `DEFINITIONS = ${literal(roots)}`,
      `METHODS = ${literal(Object.fromEntries(methods.map((m) => [m.method, { params: m.paramsId, result: m.resultId, side_effect: m.sideEffect, stream: m.stream }])))}`,
      `BEHAVIOR = ${literal(behavior)}`
    ].join("\n") + "\n";
  const rpc = [
    "# Code generated by native/codegen/generate.mjs; DO NOT EDIT.",
    "from . import generated_models as models",
    "class RPCMethods:"
  ];
  for (const m of methods)
    if (!m.stream)
      rpc.push(
        `    async def rpc_${snake(m.name)}(self, params: models.${nodes[m.paramsId].name}) -> models.${nodes[m.resultId].name}:\n        return await self._rpc(${JSON.stringify(m.method)}, params)`
      );
  return {
    "native/python/src/octo_runtime/generated_models.py": out.join("\n") + "\n",
    "native/python/src/octo_runtime/generated_rules.py": rules,
    "native/python/src/octo_runtime/generated_rpc.py": rpc.join("\n") + "\n"
  };
}
